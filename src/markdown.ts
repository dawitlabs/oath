import type { Change } from "./diff.ts";
import {
	countBreaking,
	DIFF_LABELS,
	describeCallers,
	type Labels,
} from "./format.ts";

const MARKER = "<!-- oath-diff -->";

function cell(text: string): string {
	return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function code(text: string): string {
	return text === "" ? "" : `\`${text.replaceAll("`", "'")}\``;
}

export function formatDiffMarkdown(
	changes: Change[],
	title: string,
	labels: Labels = DIFF_LABELS,
): string {
	const impact = (change: Change): string =>
		change.breaking ? `**${labels.breaking}**` : labels.safe;
	const breaking = changes.filter((change) => change.breaking).length;
	const lines = [MARKER, `### Oath behavioral diff`, "", `${cell(title)}`, ""];
	if (changes.length === 0) {
		lines.push("No behavioral differences.");
		return lines.join("\n");
	}
	lines.push(
		breaking > 0
			? `**${countBreaking(breaking, labels)}**, ${changes.length - breaking} ${labels.safe}`
			: `No ${labels.breakingPlural} · ${changes.length} ${labels.safe}`,
	);
	const groups = new Map<string, Change[]>();
	for (const change of changes) {
		const heading = [change.method, change.path, change.status ?? ""]
			.join(" ")
			.trim();
		groups.set(heading, [...(groups.get(heading) ?? []), change]);
	}
	for (const [heading, group] of groups) {
		lines.push(
			"",
			`#### ${code(heading)}`,
			"",
			"| | Field | Change | Impact | Confidence | Seen by |",
			"| --- | --- | --- | --- | --- | --- |",
		);
		for (const change of group) {
			const row = [
				change.mark,
				code(change.field ?? ""),
				cell(change.detail),
				impact(change),
				change.confidence,
				cell(describeCallers(change.callers)),
			];
			lines.push(`| ${row.join(" | ")} |`);
		}
	}
	lines.push(
		"",
		"<sub>Generated by [Oath](https://github.com/dawitlabs/oath) from observed traffic. Shapes only — no values are stored.</sub>",
	);
	return lines.join("\n");
}
